// Writes THIRD-PARTY-LICENSES.md: the licence text of every library compiled into Portique.
// Rust crates come from `cargo tree` for the Linux and Windows targets (normal dependencies only),
// npm packages from the production entries of package-lock.json. Run `npm run licenses` after changing dependencies.
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tauri = join(root, "src-tauri");
const cargo = (args) => execFileSync("cargo", [...args, "--offline", "--locked"], { cwd: tauri, encoding: "utf8", maxBuffer: 1 << 28 });

const TARGETS = ["x86_64-unknown-linux-gnu", "x86_64-pc-windows-gnu"];
const LICENSE_FILE = /^(licen[sc]e|copying|unlicense|notice)(?!.*\.(rs|toml)$)/i;

const meta = JSON.parse(cargo(["metadata", "--format-version", "1"]));
const byId = new Map(meta.packages.map((p) => [`${p.name} ${p.version}`, p]));

const used = new Set();
for (const target of TARGETS) {
  const tree = cargo(["tree", "-e", "normal", "--target", target, "--prefix", "none", "--format", "{p}"]);
  for (const line of tree.split("\n")) {
    const m = /^(\S+) v(\S+)/.exec(line);
    if (m) used.add(`${m[1]} ${m[2]}`);
  }
}

const entries = [];
for (const key of [...used].sort()) {
  const p = byId.get(key);
  if (!p || !p.source) continue; // the application itself
  entries.push({ kind: "crate", name: p.name, version: p.version, license: p.license ?? "(none declared)", dir: dirname(p.manifest_path), url: p.repository, authors: p.authors });
}

const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8")).packages;
for (const [path, v] of Object.entries(lock)) {
  if (!path || v.dev) continue;
  const dir = join(root, path);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  entries.push({ kind: "npm", name: pkg.name, version: pkg.version, license: pkg.license ?? v.license, dir, url: pkg.repository?.url ?? pkg.repository });
}

const licenceFiles = (dir) => readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort();

const groups = new Map();
const missing = [];
for (const e of entries) {
  const files = licenceFiles(e.dir);
  const text = files.map((f) => readFileSync(join(e.dir, f), "utf8").replace(/\r\n/g, "\n").trim()).join("\n\n---\n\n");
  if (!text) {
    missing.push(e);
    continue;
  }
  const k = `${e.license}\n${text}`;
  if (!groups.has(k)) groups.set(k, { license: e.license, text, items: [] });
  groups.get(k).items.push(e);
}

const out = [
  "# Third-party licences",
  "",
  "This file is generated by `scripts/gen-licenses.mjs`; do not edit it by hand.",
  "It reproduces the licence text and copyright notices of the Rust crates and npm packages compiled into Portique",
  "(Linux and Windows builds). Fonts are covered in `THIRD-PARTY-NOTICES.md`.",
  "",
  `${entries.length} packages, ${groups.size} distinct licence texts.`,
  "",
];
for (const g of [...groups.values()].sort((a, b) => a.license.localeCompare(b.license) || a.items[0].name.localeCompare(b.items[0].name))) {
  out.push(`## ${g.license}`, "");
  out.push(g.items.map((i) => `- ${i.name} ${i.version}${i.kind === "npm" ? " (npm)" : ""}`).join("\n"), "");
  out.push("```text", g.text.replace(/```/g, "'''"), "```", "");
}
if (missing.length) {
  out.push("## Packages that ship no licence file", "");
  out.push("These declare their licence in package metadata only. The licence applies as named (its full text appears under the same heading above); the authors and repository are given for the copyright notice.", "");
  out.push(missing.map((i) => `- ${i.name} ${i.version}${i.kind === "npm" ? " (npm)" : ""}: ${i.license}${i.url ? ` (${i.url})` : ""}${i.authors?.length ? `; authors: ${i.authors.join(", ")}` : ""}`).join("\n"), "");
}
writeFileSync(join(root, "THIRD-PARTY-LICENSES.md"), out.join("\n"));
console.log(`${entries.length} packages, ${groups.size} licence texts, ${missing.length} without a licence file`);
for (const m of missing) console.log(`  no file: ${m.name} ${m.version} (${m.license})`);
